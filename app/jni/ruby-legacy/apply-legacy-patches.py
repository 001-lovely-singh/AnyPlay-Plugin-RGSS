#!/usr/bin/env python3
"""Applies the AnyPlay Ruby 1.8 compatibility layer to a Ruby 3.1 source tree.

    python3 apply-legacy-patches.py <ruby-r18 source dir>

Only the r18 tree is ever patched; the clean r3 tree must stay untouched.

What it does (all idempotent, safe to run on every build):
  1. copies mkxp_legacy.inc into the tree
  2. turns legacy_prelude.rb into mkxp_legacy_prelude.h (a C byte array)
  3. appends  #include "mkxp_legacy.inc"  to vm_eval.c (once)
  4. touches vm_eval.c when 1-3 changed anything, so `make` rebuilds it
     (Ruby's dependency list does not know about the .inc file)

It does not edit any existing line of Ruby's sources, so it cannot fail because an
upstream line moved. Parser / VM changes are NOT in here yet (see README.md).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MARK = '#include "mkxp_legacy.inc"'


def read(path, mode="rb"):
    with open(path, mode) as f:
        return f.read()


def write_if_changed(path, data):
    old = read(path) if os.path.exists(path) else None
    if old == data:
        return False
    with open(path, "wb") as f:
        f.write(data)
    return True


def c_array(name, data):
    lines = []
    for i in range(0, len(data), 16):
        lines.append("  " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    body = "\n".join(lines)
    return ("/* generated by apply-legacy-patches.py from legacy_prelude.rb */\n"
            "static const char %s[] = {\n%s\n  0x00\n};\n" % (name, body)).encode()


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    tree = os.path.abspath(sys.argv[1])
    vm_eval = os.path.join(tree, "vm_eval.c")
    if not os.path.isfile(vm_eval):
        sys.exit("apply-legacy-patches: %s is not a Ruby source tree (no vm_eval.c)" % tree)
    if os.path.basename(tree) == "ruby":
        sys.exit("apply-legacy-patches: refusing to patch the clean r3 tree 'ruby'")

    changed = False
    changed |= write_if_changed(os.path.join(tree, "mkxp_legacy.inc"),
                                read(os.path.join(HERE, "mkxp_legacy.inc")))
    changed |= write_if_changed(os.path.join(tree, "mkxp_legacy_prelude.h"),
                                c_array("mkxp_legacy_prelude_src",
                                        read(os.path.join(HERE, "legacy_prelude.rb"))))

    src = read(vm_eval, "r").replace("\r\n", "\n")
    if MARK not in src:
        if not src.endswith("\n"):
            src += "\n"
        src += "\n/* AnyPlay: Ruby 1.8 compatibility layer (apply-legacy-patches.py) */\n" + MARK + "\n"
        with open(vm_eval, "w", newline="\n") as f:
            f.write(src)
        changed = True

    if changed:
        os.utime(vm_eval, None)
        print("apply-legacy-patches: applied to %s" % tree)
    else:
        print("apply-legacy-patches: already up to date (%s)" % tree)


if __name__ == "__main__":
    main()
